"""CommandCode provider profile override.

Replaces the bundled ``plugins/model-providers/commandcode/`` when installed as
a user plugin at ``$HERMES_HOME/plugins/model-providers/commandcode/``
(last-writer-wins in ``register_provider``). Registers:

``commandcode``
    ``api_mode=chat_completions`` — OpenAI-compatible endpoint.

``commandcode-anthropic``
    ``api_mode=anthropic_messages`` — Anthropic Messages API-compatible.

Both use the same ``COMMANDCODE_API_KEY`` env var and
``https://api.commandcode.ai/provider/v1`` base URL. ``capture_reasoning`` /
``annotate`` per-model metadata (image input, reasoning capability, selectable
reasoning efforts, per-model output caps) come from the checked-in
``catalog.py`` snapshot (regenerated by ``scripts/sync_catalog.py``) with
``catalog_overrides.py`` merged on top; the model ID LIST is always fetched live
from ``/models``, never hardcoded. Pricing is
injected into Hermes' ``_OFFICIAL_DOCS_PRICING`` at import (side-effect) so
``(/model`` cost badges and ``estimate_usage_cost`` resolve.
"""

