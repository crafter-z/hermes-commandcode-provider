class CommandCodeAnthropicProfile(CommandCodeProfile):
    """CommandCode — Anthropic Messages API-compatible endpoint (Bearer auth).

    Publishes ``claude-*`` ids only: the Anthropic Messages wire serves nothing
    else (every other model answers 400 "not supported on this endpoint"), and
    the OpenAI wire refuses Claude ids in turn.
    """

    def _wire_models(self, model_ids: list[str]) -> list[str]:
        return [mid for mid in model_ids if mid.startswith(_ANTHROPIC_ONLY_PREFIX)]


