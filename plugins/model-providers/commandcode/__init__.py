logger = logging.getLogger(__name__)

# Claude models are served ONLY by the Anthropic Messages wire: calling one on
# /chat/completions answers 400 ``unsupported_model`` ("must be called via
# /provider/v1/messages"). Each profile therefore publishes exactly the ids its
# own endpoint accepts (live-verified 2026-09-25).
_ANTHROPIC_ONLY_PREFIX = "claude-"

# The generated catalog is an upstream mirror; this project's own capability
# declarations live in catalog_overrides.py and are merged in here, so every
# consumer (this profile, cache enrichment, the quota plugin's lazy loader)
