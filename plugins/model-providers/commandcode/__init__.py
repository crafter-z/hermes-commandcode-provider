class CommandCodeAnthropicProfile(CommandCodeProfile):
    """CommandCode — Anthropic Messages API-compatible endpoint (Bearer auth).

    Filters the live catalog to ``claude-*`` models only.
    """

    def fetch_models(
        self,
        *,
        api_key: str | None = None,
        base_url: str | None = None,
        timeout: float = 8.0,
    ) -> list[str] | None:
        ensure_pricing()
        all_models = _fetch_commandcode_models(timeout=timeout, base_url=base_url)
        if all_models is None:
            return None
        return [m for m in all_models if m.startswith("claude-")]


